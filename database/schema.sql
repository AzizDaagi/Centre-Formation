CREATE TABLE SALLE_RESERVATION (
    ID_RESERVATION NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_STAGIAIRE NUMBER NOT NULL,
    ID_SALLE NUMBER NOT NULL,
    DATE_DEBUT DATE NOT NULL,
    DATE_FIN DATE NOT NULL,
    STATUT VARCHAR2(20) DEFAULT 'CONFIRMEE' NOT NULL,
    CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_RESERVATION_STAGIAIRE FOREIGN KEY (ID_STAGIAIRE) REFERENCES STAGIAIRE(ID_STAGIAIRE),
    CONSTRAINT FK_RESERVATION_SALLE FOREIGN KEY (ID_SALLE) REFERENCES SALLE(ID_SALLE)
)